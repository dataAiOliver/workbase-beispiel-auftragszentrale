-- Nordwerk Auftragszentrale – Basisschema (idempotent)

create table if not exists customers (
  id              bigint generated by default as identity primary key,
  customer_number text        not null,
  name            text        not null,
  email           text        not null,
  phone           text,
  street          text,
  postcode        text,
  city            text,
  country         text        not null default 'DE',
  created_at      timestamptz not null default now()
);
create index if not exists customers_email_idx on customers (lower(email));

create table if not exists products (
  id          bigint generated by default as identity primary key,
  sku         text    not null unique,
  name        text    not null,
  category    text    not null,
  price_cents integer not null check (price_cents >= 0)
);

create table if not exists orders (
  id           bigint generated by default as identity primary key,
  order_number text        not null,
  customer_id  bigint      not null references customers (id),
  status       text        not null default 'bezahlt',  -- bezahlt | versandt | erstattet | storniert
  channel      text        not null default 'webshop',
  payment_id   text,
  total_cents  integer     not null,
  currency     text        not null default 'EUR',
  note         text,
  created_at   timestamptz not null default now()
);
create index if not exists orders_created_at_idx on orders (created_at desc);
create index if not exists orders_customer_idx on orders (customer_id);

create table if not exists order_items (
  id               bigint generated by default as identity primary key,
  order_id         bigint  not null references orders (id) on delete cascade,
  product_id       bigint  references products (id),
  sku              text    not null,
  name             text    not null,
  quantity         integer not null check (quantity > 0),
  unit_price_cents integer not null
);
create index if not exists order_items_order_idx on order_items (order_id);

create table if not exists payments (
  id           bigint generated by default as identity primary key,
  order_id     bigint      not null references orders (id) on delete cascade,
  provider     text        not null default 'paynord',
  payment_id   text        not null,
  event_id     text,
  amount_cents integer     not null,
  currency     text        not null default 'EUR',
  status       text        not null,  -- succeeded | refunded
  received_at  timestamptz not null default now()
);
create index if not exists payments_order_idx on payments (order_id);
